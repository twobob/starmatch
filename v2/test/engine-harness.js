// ============================================================================
// Engine Harness
// Loads engine.js (a classic script with globals) and runs getThemeValues()
// with explicit settings, capturing everything the engine leaves in globals.
// ============================================================================

(function (root) {
  'use strict';

  const DEFAULT_SETTINGS = { orbType: 0, aoIndex: 0, poIndex: 0, tfIndex: 0, precessionFlag: 0 };

  function loadScript(src) {
    return new Promise((resolve, reject) => {
      const script = document.createElement('script');
      script.src = src;
      script.onload = resolve;
      script.onerror = () => reject(new Error('Failed to load ' + src));
      document.head.appendChild(script);
    });
  }

  function applySettings(settings, year) {
    const s = Object.assign({}, DEFAULT_SETTINGS, settings);
    root.orbType = s.orbType;
    root.aoIndex = s.aoIndex;
    root.poIndex = s.poIndex;
    root.tfIndex = s.tfIndex;
    root.precessionFlag = s.precessionFlag;
    root.nativity = year;
    root.nativityYear = year;
  }

  /**
   * Run the engine for one chart.
   * Raw (pre-normalisation) theme totals are recovered by watching writes to
   * the engine's global theme array: the last 12 writes are the normalisation
   * pass, so the value each one overwrites is that theme's raw total.
   * @param {Object} chart - { positions: [12 numbers], year }
   * @param {Object} settings - orbType, aoIndex, poIndex, tfIndex, precessionFlag
   * @returns {Object} theme, raw, numAspects, numTradFactors, tfDominant, dominantAspect
   */
  function run(chart, settings) {
    applySettings(settings, chart.year);

    const store = new Array(12).fill(0);
    const writes = [];
    root.theme = new Proxy(store, {
      set(target, key, value) {
        writes.push([key, target[key]]);
        target[key] = value;
        return true;
      }
    });

    try {
      root.getThemeValues.apply(null, chart.positions);
    } finally {
      root.theme = store;
    }

    const finalPass = writes.slice(-12);
    if (finalPass.length !== 12 || finalPass.some((w, i) => String(w[0]) !== String(i))) {
      throw new Error('Unexpected theme write pattern; engine normalisation changed?');
    }

    return {
      theme: store.slice(),
      raw: finalPass.map(w => w[1]),
      numAspects: root.numAspects.slice(0, 7),
      numTradFactors: root.numTradFactors.slice(0, 9),
      tfDominant: root.tfDominant.slice(0, 3),
      dominantAspect: root.dominantAspect
    };
  }

  /**
   * Temporarily replace one row of an engine table (e.g. ptq) while fn runs
   */
  function withTableRow(tableName, rowIndex, values, fn) {
    const table = root[tableName];
    const saved = table[rowIndex];
    table[rowIndex] = values;
    try {
      return fn();
    } finally {
      table[rowIndex] = saved;
    }
  }

  /**
   * Theme values for every chart x settings combination in StarmatchTestCases
   * @param {boolean} originalApp - feed positions as the original app did (+30°)
   */
  function computeAllCases(originalApp) {
    const { charts, settings, caseId, appShift } = root.StarmatchTestCases;
    const cases = {};
    charts.forEach(chart => {
      const input = originalApp ? Object.assign({}, chart, { positions: appShift(chart.positions) }) : chart;
      settings.forEach(s => {
        cases[caseId(chart, s)] = run(input, s).theme;
      });
    });
    return cases;
  }

  /**
   * Raw theme totals for the single-rule probe charts (fed to the engine as is)
   */
  function computeProbes() {
    const probes = {};
    root.StarmatchTestCases.probes.forEach(probe => {
      probes[probe.id] = run(probe, probe.settings).raw;
    });
    return probes;
  }

  /**
   * Source text for a fixture file (one case per line, so diffs stay readable)
   */
  function fixtureSource(label, engineSrc, cases, probes) {
    const line = (key, value) => `    ${JSON.stringify(key)}: ${JSON.stringify(value)}`;
    return [
      '// Pinned engine.js theme values. Generated by v2/test/engine-tests.html',
      '// (Download fixture button). Regenerate only when a change is intended.',
      'window.STARMATCH_FIXTURES = window.STARMATCH_FIXTURES || {};',
      `window.STARMATCH_FIXTURES.${label} = {`,
      `  "engine": ${JSON.stringify(engineSrc)},`,
      '  "cases": {',
      Object.keys(cases).map(id => line(id, cases[id])).join(',\n'),
      '  },',
      '  "probes": {',
      Object.keys(probes).map(id => line(id, probes[id])).join(',\n'),
      '  }',
      '};',
      ''
    ].join('\n');
  }

  root.EngineHarness = {
    DEFAULT_SETTINGS,
    loadScript,
    run,
    withTableRow,
    computeAllCases,
    computeProbes,
    fixtureSource
  };
})(typeof window !== 'undefined' ? window : globalThis);
